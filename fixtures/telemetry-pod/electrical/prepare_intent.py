"""Explicit actual-pod connectivity from captured selections and pin decisions.

The six bare probe features require the separate manufactured-feature consumer
contract. This recipe can resolve a draft; it cannot bypass binding-fill or any
assembly/part gate to qualify that draft.
"""
import hashlib
import json
from pathlib import Path

from agent_ee.block_adaptation import compose_flat
from agent_ee.symbol_library import parse_library, resolve_symbol


def probe_and_power_features(root):
    root = Path(root)
    proposal = json.loads((root / 'features/proposal.json').read_text())
    libraries = []
    for name in ('PodFeatures', 'power'):
        path = 'symbols/' + name + '.kicad_sym'
        libraries.append(dict(name=name, path=path,
            sha256=hashlib.sha256((root / path).read_bytes()).hexdigest()))
    components = [dict(id=p['component'], reference=p['reference'], lib_id=p['lib_id'],
        footprint=p['footprint'], value=p['net'], units=[1], pins={p['pin']: p['net']})
        for p in proposal['physical']]
    # Native ERC cannot follow power through passive inductors or the PMOS.
    # These flags declare those actual supply paths, not measured rail validity.
    for n, net in enumerate(('GND', 'POD_12V_IN', 'POD_12V_PROTECTED', '+3V3', 'PRE_6V3'), 1):
        components.append(dict(id='power-flag/' + str(n), reference='#FLG0' + str(n),
            lib_id='power:PWR_FLAG', footprint='', value='PWR_FLAG', units=[1], pins={'1': net}))
    return dict(libraries=libraries, components=components)


def prepare(root, features):
    root = Path(root)
    load = lambda path: json.loads((root / path).read_text())
    rows = load('electrical-selections.json')['parts']
    allocation = load('core/pin-allocation.json')
    power = load('power-source/pins-and-values-v2.json')
    support = load('support-decisions.json')
    parts = {p['id']: p for p in load('parts-electrical.json')['parts']}
    cad = load('cad/assignments.json')
    can_ids = {'can/U307', 'can/C308', 'can/D4', 'can/R9'}
    # Source-derived CAN libraries are generated by the composition API below.
    libraries = [p for p in cad['libraries'] if not p['name'].startswith('Block_')]
    libraries.extend(features['libraries'])
    captured = {p['path']: (root / p['path']).read_bytes() for p in libraries}
    components, mappings = [], {}
    source_pins = {c['reference']: c['pins'] for c in allocation['components']}
    passive_nodes = {p['reference']: p['nodes'] for p in power['passives']}
    values = {p['reference']: p['value'] for p in power['passives']}
    passive_nodes.update({p['reference']: p['nodes'] for p in support['parts']})
    values.update({p['reference']: {'C694521': '22uF', 'C76711': '100nF',
                                  'C76706': '1uF', 'C95204': '10k'}[p['lcsc']]
                   for p in support['parts']})

    def net_name(value):
        # These are declared source phrases/aliases, not fuzzy text inference.
        return {'POD_SENSOR_RETURN': 'GND', 'POD_5V_SENSOR at connector': 'POD_5V_SENSOR',
                'REVERSE_GATE (anode)': 'REVERSE_GATE',
                'POD_12V_PROTECTED (cathode)': 'POD_12V_PROTECTED'}.get(value, value)

    for p in rows:
        if p['component'] in can_ids:
            continue
        ref = p['reference']
        components.append(dict(id=p['component'], reference=ref, lib_id=p['lib_id'],
            value=values.get(ref, parts[p['id']]['mpn']), footprint=p['footprint'], units=[1]))
        if ref in source_pins:
            pins = {pin['number']: pin['net'] for pin in source_pins[ref]}
            if ref == 'U1':
                if pins['16'] != 'GND':
                    raise ValueError('GPIO46 source strap changed')
                pins['16'] = 'MCU_BOOT46'
        elif ref in power['pins']:
            pins = dict(power['pins'][ref])
            if 'EP' in pins:
                pins.pop('EP')
                pins['9'] = 'GND'
            if 'tab' in pins:
                if pins.pop('tab') != pins['2']:
                    raise ValueError('drain tab differs from pin2')
            for text in power['open_pins'].get(ref, []):
                number = text.split(' ', 1)[0]
                if number in pins:
                    raise ValueError('open pin is also connected')
                pins[number] = None
        elif ref in passive_nodes:
            first, second = passive_nodes[ref]
            # Stock D_Zener pin1=K, pin2=A; the proposal lists anode then cathode.
            pins = {'1': second, '2': first} if ref == 'D2' else {'1': first, '2': second}
        elif ref == 'J1':
            pins = {p['pin']: p['net'] for p in allocation['harness_boundaries']}
            pins.update({number: None for number in allocation['harness_no_connects']})
        elif ref == 'J2':
            pins = {'1': 'POD_GNSS_RF', '2': 'GND'}
        else:
            raise ValueError('no explicit pin mapping for ' + ref)
        mappings[p['component']] = {number: net_name(net) if net is not None else None for number, net in pins.items()}
    for feature in features['components']:
        components.append({k: feature[k] for k in ('id', 'reference', 'lib_id', 'value', 'footprint', 'units')})
        mappings[feature['id']] = feature['pins']
    # Each selected physical pin must be explicitly accounted for; no defaults.
    for comp in components:
        lib, symbol = comp['lib_id'].split(':')
        source = next(p for p in libraries if p['name'] == lib)
        raw = captured[source['path']]
        pins, _, _ = resolve_symbol(parse_library(raw), symbol, source['path'], hashlib.sha256(raw).hexdigest())
        if set(mappings[comp['id']]) != {p['number'] for p in pins}:
            raise ValueError('physical pin inventory differs for ' + comp['reference'])
    nets, no_connects = {}, []
    for component, pins in mappings.items():
        for number, net in pins.items():
            terminal = dict(component=component, pin=dict(number=number))
            if net is None:
                no_connects.append(terminal)
            else:
                if not isinstance(net, str) or not net.strip():
                    raise ValueError('empty net')
                nets.setdefault(net, []).append(terminal)
    intent = dict(schema='agent-ee.connectivity-intent/1', libraries=libraries, components=components,
        nets=[dict(id='net-' + str(n), name=name, terminals=terminals) for n, (name, terminals) in enumerate(sorted(nets.items()), 1)],
        no_connects=no_connects)
    previous = load('core/can-source/instance.json')
    request = dict(id='can', block='core/can-source/block', composition='core/can-source/composition.json',
        reference_ranges=previous['reference_ranges'], sheet='telemetry-pod.kicad_sch',
        requirements=previous['requirements'])
    bindings = {'+3V3': '+3V3', '+5V': '+5V_CAN', 'CAN+': 'POD_CAN_P', 'CAN-': 'POD_CAN_N',
                'GND': 'GND', 'S': 'GND', 'TXD': 'TWAI_TX', 'RXD': 'TWAI_RX'}
    composed = compose_flat(root, intent, [request], {'can': bindings}, captured_libraries=captured)
    # Keep the original source bindings in a distinct recorded adaptation. The
    # canonical purchasing fields must subsequently come from binding_fill.
    adaptations = []
    for component in composed['intent']['components']:
        if component['id'] in can_ids:
            adaptations.append(dict(component=component['id'], reference=component['reference'],
                source_fields=component.pop('part_binding', {}),
                reason='Replace source purchasing-property representation with exact captured manifest fields through binding_fill; source identity and nets remain bound to immutable block_instances.'))
    return dict(**composed, part_property_adaptations=adaptations)
