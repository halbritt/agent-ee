import hashlib
import copy
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('recovery_runtime', ROOT / 'scripts/recovery_runtime.py')
runtime = importlib.util.module_from_spec(spec)
spec.loader.exec_module(runtime)


class RecoveryInputTests(unittest.TestCase):
    def test_cancelled_native_capture_is_readiness_only_when_no_search_executed(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            job = {'status': 'cancelled', 'preflight': {'python': '3.12.3'}, 'identity': 'bound-input',
                   'engine': {'interruption': 'cancelled', 'exit_code': None, 'counters': {}, 'seeds': []}}
            (directory / 'capture.json').write_text(json.dumps({'footprints': [1, 2, 3]}))
            cases = [('cancelled', 1, {}, True), ('refused', 1, {}, False),
                     ('cancelled', None, {}, False),
                     ('cancelled', 1, {'counters': {'evaluations': 10}}, False),
                     ('cancelled', 1, {'seeds': [{'seed': 1}]}, False)]
            for status, exit_code, engine, expected in cases:
                with self.subTest(status=status, exit_code=exit_code, engine=engine):
                    report = copy.deepcopy(job)
                    report['status'] = status
                    report['engine'].update(engine)
                    (directory / 'job-report.json').write_text(json.dumps(report))
                    selected = runtime.cancelled_preflight(directory, exit_code)
                    self.assertEqual(selected['status'], status)
                    self.assertEqual(selected['runtime_ready_before_cancellation'], expected)
            (directory / 'capture.json').unlink()
            self.assertFalse(runtime.cancelled_preflight(directory, 1)['runtime_ready_before_cancellation'])

    def test_verify_reports_missing_and_changed_captures_without_substitution(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            capture = root / 'inputs'
            capture.mkdir()
            (capture / 'one').write_bytes(b'original')
            manifest = root / 'manifest.json'
            manifest.write_text(json.dumps({'files': {'one': {'sha256': hashlib.sha256(b'original').hexdigest(),
                                                             'bytes': 8}}}))
            with patch.object(runtime, 'MANIFEST', manifest):
                runtime.verify(capture)
                (capture / 'one').write_bytes(b'altered!')
                with self.assertRaisesRegex(ValueError, 'one: differs from captured bytes'):
                    runtime.verify(capture)
                (capture / 'one').unlink()
                with self.assertRaisesRegex(ValueError, 'one: missing file'):
                    runtime.verify(capture)
                outside = root / 'outside'
                outside.write_bytes(b'original')
                (capture / 'one').symlink_to(outside)
                with self.assertRaisesRegex(ValueError, 'link or escaped input root'):
                    runtime.verify(capture)

    def test_manifest_binds_the_exact_esp_prog_config_inputs(self):
        manifest = json.loads(runtime.MANIFEST.read_text())
        # The planning baseline is an independent frozen source, not regenerated by this harness.
        baseline = json.loads((ROOT / 'docs/planning/2026-10-25-recovery/baseline.json').read_text())
        for entry in baseline['esp_prog_frozen_config']['inputs'].values():
            path = Path(entry['path']).relative_to('/opt/agent-ee').as_posix()
            self.assertEqual(manifest['files'][path]['sha256'], entry['sha256'])
