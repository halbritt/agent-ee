"""Coordinator-owned Stage-A candidate sets from a forward-annotated native board.

Historical immutable block inputs keep their original contract. This opt-in path
binds immutable recipes at preparation, then verifies generated bytes against a
board-bound report before the ordinary placement consumer can use them.
"""
import argparse
import copy
import json
import multiprocessing
import os
import time
import resource
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path
import subprocess

from . import block_variants, blocks, stage_receipts
from .storage import digest, identity, read_json, write_json

REPORT = 'agent-ee.block-variant-producer/1'
STEP = 'block-variants'


def output_paths(section):
    return [section['netlist'], section['side_eligibility'], section['contract'],
            *section['candidates'], section['stage_owned']['report']]


def immutable_paths(section):
    return [section['allocation'], section['arrangement'],
            section['stage_owned']['eligibility'], section['stage_owned']['contract']]


def context(scope, declaration, mutable_inputs):
    from .placement_adapter import validate_declaration
    # These are precisely the scope fields used by placement policy binding.
    return {'scope': {key: copy.deepcopy(scope[key]) for key in ('board', 'schematic', 'checks', 'envelope')
                      if key in scope},
            'declaration': validate_declaration(declaration), 'mutable_inputs': sorted(mutable_inputs)}


def _argv(ctx):
    return ['/usr/bin/env', 'PYTHONPATH=/tool/agent-ee', '/usr/bin/python3', '-B', '-P', '-m',
            'agent_ee.block_variant_stage', '--context', json.dumps(ctx, sort_keys=True, separators=(',', ':'))]


def step(source_root, *, scope, declaration, mutable_inputs, timeout_s=600):
    """A schematic-stage producer: forward annotation precedes it in the same turn."""
    from .tool_source import snapshot
    ctx = context(scope, declaration, mutable_inputs)
    section = ctx['declaration']['blocks']
    return stage_receipts.validate_step({
        'schema': 'agent-ee.stage-step/1', 'step': STEP, 'stage': 'schematic',
        'argv': _argv(ctx), 'mounts': [{'source': str(snapshot(source_root)), 'at': '/tool/agent-ee'}],
        'source': '/tool/agent-ee', 'version_argv': ['/usr/bin/kicad-cli', 'version'],
        'writes': {path: 'out/' + path for path in output_paths(section)},
        'artifacts': ['out', 'variants'], 'adoptable_exits': [0], 'timeout_s': timeout_s})


def validate_step_contract(spec, scope, declaration, mutable_inputs):
    ctx = context(scope, declaration, mutable_inputs)
    outputs = output_paths(ctx['declaration']['blocks'])
    if (spec['step'] != STEP or spec['stage'] != 'schematic' or spec['argv'] != _argv(ctx)
            or spec['writes'] != {path: 'out/' + path for path in outputs}
            or spec['source'] != '/tool/agent-ee' or spec['adoptable_exits'] != [0]
            or spec['artifacts'] != ['out', 'variants']):
        raise ValueError('block-variants step differs from its owned producer contract')


def _read(inputs, files, path):
    target = Path(inputs) / path
    if target.is_symlink() or not target.is_file() or path not in files or digest(target) != files[path]:
        raise ValueError(f'captured block producer file changed: {path}')
    return target.read_bytes()


def dependencies(manifest, mutable_inputs):
    return {path: sha for path, sha in sorted(manifest['files'].items()) if path not in mutable_inputs}


def consume(section, manifest, inputs, mutable_inputs, declaration, *, require_produced):
    """Stable campaign recipe binding plus separately checked stage-owned outputs.

    The candidate manifest authenticates the report bytes; the report authenticates
    every output against this exact native board, schematic and immutable inputs.
    Stage receipts independently verify who produced/adopted those candidate bytes.
    """
    owner = section['stage_owned']
    inputs = Path(inputs)
    sources = dependencies(manifest, mutable_inputs)
    for path in sources:
        _read(inputs, manifest['files'], path)
    stable = {'stage_owned': copy.deepcopy(owner), 'inputs': sources,
              'context_sha256': identity(context(manifest['scope'], declaration, mutable_inputs))}
    report = json.loads(_read(inputs, manifest['files'], owner['report']))
    if report == {'schema': REPORT, 'status': 'pending'}:
        if require_produced:
            raise ValueError('stage-owned block variants have not been produced')
        if any(_read(inputs, manifest['files'], path) != b'' for path in output_paths(section)
               if path != owner['report']):
            raise ValueError('pending block producer outputs must be empty placeholders')
        return stable, False
    expected_keys = {'schema', 'status', 'context_sha256', 'inputs', 'board', 'schematic', 'outputs'}
    if not isinstance(report, dict) or set(report) != expected_keys or report['schema'] != REPORT or report['status'] != 'produced':
        raise ValueError('invalid block variant producer report')
    if report['context_sha256'] != stable['context_sha256'] or report['inputs'] != sources:
        raise ValueError('block variant producer recipe or immutable inputs changed')
    for key in ('board', 'schematic'):
        path = manifest['scope'][key]
        if report[key] != {'path': path, 'sha256': manifest['files'][path]}:
            raise ValueError(f'stage-owned block variants are stale for the current {key}')
        _read(inputs, manifest['files'], path)
    expected = set(output_paths(section)) - {owner['report']}
    if not isinstance(report['outputs'], dict) or set(report['outputs']) != expected:
        raise ValueError('block variant producer output inventory changed')
    for path, sha in report['outputs'].items():
        if sha != manifest['files'][path]:
            raise ValueError(f'stage-owned block output digest changed: {path}')
        _read(inputs, manifest['files'], path)
    for path in section['candidates']:
        if read_json(inputs / path).get('schema') != block_variants.SCHEMA:
            raise ValueError('stage-owned producer requires native /1 candidate sets')
    return stable, True


# Spawned workers own independent native KiCad state. The enclosing stage's
# admitted sandbox/cgroup and process-group timeout own the entire pool.
MAX_BLOCK_WORKERS = 8
_WORKER_INPUTS = None


def _worker_inputs(arguments):
    global _WORKER_INPUTS
    _WORKER_INPUTS = arguments


def _produce_block(job):
    index, block_id, directory = job
    source, capture, inventory, derivation, policy, eligibility = _WORKER_INPUTS
    started = time.monotonic()
    record = {'block': block_id, 'pid': os.getpid(), 'status': 'running'}
    try:
        document = block_variants.produce(source, capture, inventory, derivation, block_id, policy, eligibility, directory)
        record['status'] = 'completed'
        record['variants'] = {face: advisory_summary(variant['candidate']['grade']['electrical_locality'])
                              for face, variant in document['variants'].items()
                              if variant['status'] == 'packed' and variant['candidate']['grade'].get('electrical_locality')}
        return index
    except BaseException as exc:
        record.update(status='failed', error=f'{type(exc).__name__}: {exc}')
        raise
    finally:
        record.update(elapsed_s=time.monotonic() - started,
                      peak_rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
        Path(directory).mkdir(parents=True, exist_ok=True)
        write_json(Path(directory) / 'worker.json', record)


def _produce_blocks(source, capture, inventory, derivation, policy, eligibility, directory):
    """Complete every private set before the caller publishes any campaign output."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=False)
    jobs = [(i, block['id'], directory / str(i)) for i, block in enumerate(derivation['blocks'])]
    workers = min(MAX_BLOCK_WORKERS, max(1, os.cpu_count() or 1), len(jobs))
    if not workers:
        raise ValueError('block producer needs at least one derived block')
    started = time.monotonic()
    summary = {'workers': workers, 'blocks': len(jobs), 'status': 'running', 'completed': []}
    write_json(directory / 'production.json', summary)
    with ProcessPoolExecutor(max_workers=workers, mp_context=multiprocessing.get_context('spawn'),
            initializer=_worker_inputs, initargs=((str(source), capture, inventory, derivation, policy, eligibility),)) as pool:
        futures = [pool.submit(_produce_block, job) for job in jobs]
        for future in as_completed(futures):
            summary['completed'].append(future.result())
            summary['completed'].sort()
            summary['elapsed_s'] = time.monotonic() - started
            write_json(directory / 'production.json', summary)
    summary.update(status='completed', elapsed_s=time.monotonic() - started)
    write_json(directory / 'production.json', summary)
    return summary


def advisory_summary(check):
    """A passing decision is distinct from satisfying every engineering target."""
    rows = copy.deepcopy(check.get('advisories', []))
    return {'status': check['status'], 'advisory_count': len(rows),
            'exceeded_advisory_count': sum(row.get('exceeded') is True for row in rows), 'advisories': rows}


def produce_stage(inputs, work, ctx):
    """Run inside the ordinary stage sandbox; publish only declared output files."""
    from . import placement_adapter as adapter
    from .native_netlist import read_native_inventory, read_sheet_names
    from .placement_probe import extract
    inputs, work = Path(inputs), Path(work)
    files, other = stage_receipts.file_tree(inputs)
    if other:
        raise ValueError('block producer inputs contain links or non-files')
    manifest = {'scope': ctx['scope'], 'files': files}
    declaration, mutable = ctx['declaration'], ctx['mutable_inputs']
    bound = adapter.bind_declaration(declaration, manifest, mutable)
    section = bound['blocks']
    for path in output_paths(section):
        if path in (bound['board'], bound['schematic'], bound['policy']):
            raise ValueError('block producer output collides with a design or policy input')
    # Use the consumer's own policy composition, including envelope/locality/mechanics.
    plain = {key: value for key, value in declaration.items() if key != 'blocks'}
    _, _, policy, _, refs = adapter.binding(plain, manifest, inputs, mutable)
    policy = adapter.request_policy(policy, refs)
    capture = extract(inputs / bound['board'])
    original_hash = capture['board_sha256']
    eligibility = read_json(inputs / section['stage_owned']['eligibility'])
    contract = read_json(inputs / section['stage_owned']['contract'])
    # Templates are explicit unbound inputs, not historical board-bound captures.
    if eligibility.get('sources', {}).get('board_sha256') is not None or contract.get('allocation', {}).get('board_sha256') is not None:
        raise ValueError('stage-owned templates must be unbound; historical board bindings are not rewritten')
    eligibility = copy.deepcopy(eligibility)
    eligibility.setdefault('sources', {})['board_sha256'] = original_hash
    contract = copy.deepcopy(contract)
    if contract.get('eligibility') != read_json(inputs / section['stage_owned']['eligibility']):
        raise ValueError('contract and eligibility templates differ')
    contract['eligibility'] = eligibility
    contract['allocation']['board_sha256'] = original_hash
    if contract.get('relationships') != policy.get('electrical_locality'):
        raise ValueError('block contract relationships differ from bound placement policy')
    from .block_contract import _contract
    _contract(capture, contract)
    out = work / 'out'
    out.mkdir(parents=True, exist_ok=False)
    netlist = out / section['netlist']
    netlist.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(['kicad-cli', 'sch', 'export', 'netlist', '--format', 'kicadxml',
                             '-o', str(netlist), str(inputs / bound['schematic'])],
                            capture_output=True, text=True, timeout=120)
    (work / 'netlist-export.stdout').write_text(result.stdout)
    (work / 'netlist-export.stderr').write_text(result.stderr)
    if result.returncode:
        raise ValueError(f'native block netlist export failed: exit {result.returncode}')
    inventory = read_native_inventory(netlist)
    allocation = _read(inputs, files, section['allocation'])
    derivation = blocks.derive(inventory, read_sheet_names(netlist), capture,
                              inventory_sha256=digest(netlist), allocation_raw=allocation)
    if len(derivation['blocks']) != len(section['candidates']):
        raise ValueError('stage-owned candidate paths must cover every derived block exactly once')
    for key, value in [('side_eligibility', eligibility), ('contract', contract)]:
        target = out / section[key]
        target.parent.mkdir(parents=True, exist_ok=True)
        write_json(target, value)
    variants = work / 'variants'
    _produce_blocks(inputs / bound['board'], capture, inventory, derivation, policy, eligibility, variants)
    # The parent independently admits every completed set. No partially finished
    # worker file is installed at a campaign output path.
    for index, block in enumerate(derivation['blocks']):
        document = read_json(variants / str(index) / 'candidate-set.json')
        block_variants.validate(document, capture, inventory, derivation, policy, eligibility)
        if document['block_id'] != block['id']:
            raise ValueError('parallel block result identity differs from its declared slot')
    if stage_receipts.file_tree(inputs) != (files, []):
        raise ValueError('block producer source inputs changed during production')
    from .block_contract import check_complete
    write_json(variants / 'source-contract-advisories.json', {
        'scope': 'source coordinates before placement; not candidate acceptance',
        **advisory_summary(check_complete(capture, contract))})
    for index, path in enumerate(section['candidates']):
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        write_json(target, read_json(variants / str(index) / 'candidate-set.json'))
    report = {'schema': REPORT, 'status': 'produced', 'context_sha256': identity(ctx),
              'inputs': dependencies(manifest, mutable),
              'board': {'path': bound['board'], 'sha256': files[bound['board']]},
              'schematic': {'path': bound['schematic'], 'sha256': files[bound['schematic']]},
              'outputs': {path: digest(out / path) for path in output_paths(section)
                          if path != section['stage_owned']['report']}}
    target = out / section['stage_owned']['report']
    target.parent.mkdir(parents=True, exist_ok=True)
    write_json(target, report)
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--context', required=True)
    args = parser.parse_args(argv)
    produce_stage('/candidate', '/work', json.loads(args.context))


if __name__ == '__main__':
    main()
